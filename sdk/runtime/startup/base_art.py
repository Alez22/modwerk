#!/usr/bin/env python3
"""The base's startup art as C data for boot_anim.c (sdk/machines/octatrack/elekloader).

Reads the shared artwork (artwork.json: the mark and the wordmark) and the base's own layer
(base.json: the layout shift, the font, NEW and the version) and writes boot_art.h. final_pixels()
is the frame the animation ends on, for the host test and the emulator check. Authored data only.
"""
import json
import math
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent


def load():
    return json.loads((HERE / 'artwork.json').read_text()), json.loads((HERE / 'base.json').read_text())


def text_cells(base, version):
    """Each glyph of NEW and the version: (item, x, y, w, h, pixels) on the screen."""
    if not re.fullmatch(r'\d+\.\d+\.\d+', version):
        raise ValueError('The base version is major.minor.patch')
    font, cells = base['font'], []
    for n, item in enumerate(base['text']):
        string = item['string'].replace('{version}', version)
        scale, gap = item['scale'], item['gap']
        width = sum(len(font[c][0]) * scale for c in string) + gap * (len(string) - 1)
        x = item['x'] - width // 2
        for char in string:
            glyph = font[char]
            w, h = len(glyph[0]) * scale, len(glyph) * scale
            ink = [(x + gx * scale + dx, item['y'] + gy * scale + dy) for gy, row in enumerate(glyph)
                   for gx, c in enumerate(row) if c == '#' for dy in range(scale) for dx in range(scale)]
            cells.append((n, x, item['y'], w, h, ink))
            x += w + gap
    return cells


def layers(version):
    art, base = load()
    dy = base['layout']['dy']
    mx, my = art['mark']['x'], art['mark']['y'] + dy
    mark = {(x, y) for y, row in enumerate(art['mark']['rows']) for x, c in enumerate(row) if c == '#'}
    boxes = [(gx, gy) for gy in range(3) for gx in range(3) if (gx, gy) != (2, 2)]
    in_box = lambda x, y, gx, gy: 6 + 8 * gx <= x < 12 + 8 * gx and 6 + 8 * gy <= y < 12 + 8 * gy
    tiles = {p for p in mark if any(in_box(*p, *b) for b in boxes)}
    disc = {(x, y) for x, y in mark if x >= 26 and y >= 26}
    frame = mark - tiles - disc
    wordmark = {(art['wordmark']['x'] + x, art['wordmark']['y'] + dy + y) for y, row in enumerate(art['wordmark']['rows'])
                for x, c in enumerate(row) if c == '#'}
    cells = text_cells(base, version)
    every = {(mx + x, my + y) for x, y in mark} | wordmark | {p for c in cells for p in c[5]}
    if len(every) != len(mark) + len(wordmark) + sum(len(c[5]) for c in cells):
        raise ValueError('The startup text overlaps the mark or the wordmark')
    if any(not (0 <= x < 128 and 0 <= y < 64) for x, y in every):
        raise ValueError('The startup art leaves the screen')
    return art, base, dy, (mx, my), tiles, disc, frame, cells


def final_pixels(version):
    art, base, dy, (mx, my), tiles, disc, frame, cells = layers(version)
    wordmark = {(art['wordmark']['x'] + x, art['wordmark']['y'] + dy + y) for y, row in enumerate(art['wordmark']['rows'])
                for x, c in enumerate(row) if c == '#'}
    return {(mx + x, my + y) for x, y in tiles | disc | frame} | wordmark | {p for c in cells for p in c[5]}


def header(version):
    art, base, dy, (mx, my), tiles, disc, frame, cells = layers(version)
    dx0, dy0 = min(x for x, _ in disc), min(y for _, y in disc)
    dw, dh = max(x for x, _ in disc) - dx0 + 1, max(y for _, y in disc) - dy0 + 1
    disc_rows = [sum(1 << (dw - 1 - x) for x in range(dw) if (dx0 + x, dy0 + y) in disc) for y in range(dh)]

    # Every pixel of the frame and the eight tiles is a particle that sets off at its own time (ms): the
    # frame clockwise from the top over 300 ms, the tiles from the middle one round the ring, 45 ms apart.
    def phase(x, y):
        return int(math.atan2(x - 16.5, 16.5 - y) % (2 * math.pi) / (2 * math.pi) * 256) & 255
    ring = ((1, 2, 3), (8, 0, 4), (7, 6, 5))
    turns = sorted((ring[gy][gx], gx, gy) for gy in range(3) for gx in range(3) if (gx, gy) != (2, 2))
    tile_delay = [150 + 45 * n for n in range(8)]
    rank = {(gx, gy): n for n, (_, gx, gy) in enumerate(turns)}
    dots = [(mx + x, my + y, phase(x, y) * 300 // 256) for x, y in frame]
    dots += [(mx + x, my + y, tile_delay[rank[(x - 6) // 8, (y - 6) // 8]]) for x, y in tiles]
    dots.sort(key=lambda d: d[2])
    wx, wy = art['wordmark']['x'], art['wordmark']['y'] + dy
    columns = [sum(1 << y for y in range(15) if art['wordmark']['rows'][y][x] == '#') for x in range(110)]
    ink = [p for c in cells for p in c[5]]
    glyphs, first = [], 0
    for item, x, y, w, h, pixels in cells:
        glyphs.append('{%d, %d, %d, %d, %d, %d, %d}' % (item, x, y, w, h, first, len(pixels)))
        first += len(pixels)
    out = ['/* Generated by sdk/runtime/startup/base_art.py from artwork.json and base.json; do not edit. */',
           '#define BOOT_VERSION "%s"' % version,
           '#define BOOT_MARK_X %d' % mx, '#define BOOT_MARK_Y %d' % my,
           '#define BOOT_DISC_X %d' % (mx + dx0), '#define BOOT_DISC_Y %d' % (my + dy0),
           '#define BOOT_DISC_W %d' % dw, '#define BOOT_DISC_H %d' % dh,
           '#define BOOT_WORD_X %d' % wx, '#define BOOT_WORD_Y %d' % wy,
           '#define BOOT_DOTS %d' % len(dots), '#define BOOT_GLYPHS %d' % len(cells),
           'static const uint8_t boot_disc[%d] = {%s};' % (dh, ', '.join(map(str, disc_rows))),
           'struct boot_dot { uint8_t x, y; uint16_t delay; };',
           'static const struct boot_dot boot_dots[%d] = {%s};' % (len(dots), ', '.join('{%d, %d, %d}' % d for d in dots)),
           'static const uint16_t boot_word[110] = {%s};' % ', '.join(map(str, columns)),
           'struct boot_glyph { uint8_t item, x, y, w, h; uint16_t first, count; };',
           'static const struct boot_glyph boot_glyph[%d] = {%s};' % (len(cells), ', '.join(glyphs)),
           'static const uint8_t boot_ink[%d][2] = {%s};' % (len(ink), ', '.join('{%d, %d}' % p for p in ink))]
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    import sys
    sys.stdout.write(header(sys.argv[1]))
