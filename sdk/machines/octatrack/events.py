"""The Octatrack's events at base-owned stock sites, from events.json.

    python3 -B sdk/machines/octatrack/events.py --check   # generated files are current
    python3 -B sdk/machines/octatrack/events.py --write   # regenerate them

Generates the base's dispatch (elekloader/runtime_events.s), the loader's
table header (elekloader/runtime_events.h), the SDK header modules include
(include/modwerk_events.h) and the reference table (EVENTS.md). The base patches
each site with a jmp to its dispatch; a runtime package subscribes (loader.h's
hook words past RUNTIME_ENC, build.py) and never patches the site. An event with
no site ("site": null) is raised by a module instead: it calls the base's
modwerk_raise_<event>(), which runs every handler and returns their answers OR'd
(runtime.json "raise"; the package is then bound to that base's address).
"""
import argparse
import json
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
REGISTRY = HERE / 'events.json'
FIRST = 4  # loader.h: RUNTIME_TICK, RUNTIME_DRAW, RUNTIME_KEY, RUNTIME_ENC come first
SAVED = 20  # d0-d1/a0-a2 the dispatch keeps for the stock continuation
OUTPUTS = {'elekloader/runtime_events.s': 'asm', 'elekloader/runtime_events.h': 'loader',
           'include/modwerk_events.h': 'sdk', 'EVENTS.md': 'markdown'}


def load(path=REGISTRY):
    """The validated registry: {'sites': {address: site}, 'events': [event, ...]} with ints for addresses."""
    doc = json.loads(Path(path).read_text())
    if doc.get('schema') != 1 or doc.get('device') != 'octatrack' or doc.get('os') != '1.40C':
        raise ValueError('events.json: schema 1 for the Octatrack 1.40C')
    sites = {}
    for s in doc['sites']:
        at = int(s['site'], 16)
        if at in sites or at & 1 or s['length'] < 6 or s['length'] & 1 or not re.fullmatch('[0-9a-f]{64}', s['guard']):
            raise ValueError('events.json: site %s needs an even length of 6 or more and a SHA-256 guard' % s['site'])
        sites[at] = dict(s, site=at)
    events = []
    for i, e in enumerate(doc['events']):
        if e['site'] is None:  # raised by a module through modwerk_raise_<event>: no stock bytes, no arguments yet
            if (e['index'] != FIRST + i or e.get('length') or e['args'] or e['results'] != 'or'
                    or not re.fullmatch('ev_[a-z0-9_]+', e['event'])):
                raise ValueError('events.json: raised event %s needs the next hook index, no length or arguments, '
                                 'and results "or"' % e['event'])
            events.append(dict(e, site=None, length=0))
            continue
        at = int(e['site'], 16)
        if (e['index'] != FIRST + i or at not in sites or e['length'] != sites[at]['length']
                or not re.fullmatch('ev_[a-z0-9_]+', e['event'])):
            raise ValueError('events.json: %s needs the next hook index and a declared site' % e['event'])
        if e['results'] != 'notify' and (e['results'].get('0') != 'next' or e['results'].get('*') not in ('tail', 'done')
                                         or any(v not in ('tail', 'done') for k, v in e['results'].items() if k != '0')):
            raise ValueError('events.json: %s results map 0 to next and every other value to tail or done' % e['event'])
        if any(v == 'done' for v in (e['results'].values() if e['results'] != 'notify' else ())) and not sites[at]['done']:
            raise ValueError('events.json: %s drops calls at a site with no done code' % e['event'])
        for a in e['args']:
            if a != '&d0' and not re.fullmatch(r'site\+\d+', a):
                raise ValueError('events.json: %s argument %s is &d0 or site+N' % (e['event'], a))
        events.append(dict(e, site=at))
    return dict(sites=sites, events=events)


def index(name, registry=None):
    """The hook index a package carries for an event."""
    for e in (registry or load())['events']:
        if e['event'] == name:
            return e['index']
    raise ValueError('No event %s in sdk/machines/octatrack/events.json' % name)


def raised(registry=None):
    """The events modules raise themselves: {event name: the base's entry symbol}."""
    return {e['event']: 'modwerk_raise_' + e['event'] for e in (registry or load())['events'] if e['site'] is None}


def base_sites(registry=None):
    """The patches the base build writes: (address, length, guard SHA-256, the dispatch symbol it jumps to)."""
    reg = registry or load()
    return [(at, s['length'], s['guard'], 'modwerk_site_%08x' % at) for at, s in sorted(reg['sites'].items())]


def asm(reg):
    out = ['| SPDX-License-Identifier: GPL-3.0-or-later\n'
           '| Generated by sdk/machines/octatrack/events.py from events.json: do not edit.\n'
           '| The base owns these stock sites: each is a jmp here. Handlers come from the\n'
           '| loader\'s ordered tables (modwerk_runtime_event_row, one per event, 0-ended),\n'
           '| with the C convention; d0-d1/a0-a2 are kept for the stock continuation.\n'
           '        .text\n        .globl  modwerk_events_code, modwerk_events_code_end\n'
           'modwerk_events_code:\n']
    for at, s in sorted(reg['sites'].items()):
        name = '%08x' % at
        out.append('\n| ---- %#010x: %s\n        .globl  modwerk_site_%s\nmodwerk_site_%s:\n' % (
            at, ', '.join(e['event'] for e in reg['events'] if e['site'] == at), name, name))
        out += ['        %s\n' % line for line in s['head']]
        out.append('        lea     -%d(%%sp),%%sp\n        movem.l %%d0-%%d1/%%a0-%%a2,(%%sp)\n' % SAVED)
        for e in (e for e in reg['events'] if e['site'] == at):
            k, loop, end = e['index'] - FIRST, '.L%s_%s' % (name, e['event']), '.L%s_%s_end' % (name, e['event'])
            out.append('| %s: %s\n        movea.l modwerk_runtime_event_row+%d,%%a2\n%s:\n'
                       '        move.l  (%%a2)+,%%d0\n        beq     %s\n' % (e['event'], e['prototype'], 4 * k, loop, end))
            pushed = 0
            for a in reversed(e['args']):
                if a == '&d0':
                    out.append('        pea     %d(%%sp)\n' % pushed)
                else:
                    out.append('        move.l  %d(%%sp),-(%%sp)\n' % (SAVED + int(a[5:]) + pushed))
                pushed += 4
            out.append('        movea.l %%d0,%%a0\n        jsr     (%%a0)\n        lea     %d(%%sp),%%sp\n' % pushed)
            if e['results'] == 'notify':
                out.append('        bra     %s\n' % loop)
            else:
                out.append('        tst.l   %%d0\n        beq     %s\n' % loop)
                for value, action in sorted((k, v) for k, v in e['results'].items() if k not in ('0', '*')):
                    out.append('        cmpi.l  #%d,%%d0\n        beq     .L%s_%s\n' % (int(value), name, action))
                out.append('        bra     .L%s_%s\n' % (name, e['results']['*']))
            out.append('%s:\n' % end)
        for action in ('tail', 'done'):
            if s[action]:
                out.append('.L%s_%s:\n        movem.l (%%sp),%%d0-%%d1/%%a0-%%a2\n        lea     %d(%%sp),%%sp\n' % (name, action, SAVED))
                out += ['        %s\n' % line for line in s[action]]
    for e in (e for e in reg['events'] if e['site'] is None):
        k, loop, end = e['index'] - FIRST, '.Lraise_%s' % e['event'], '.Lraise_%s_end' % e['event']
        out.append('\n| ---- raised by a module: %s: %s; every handler runs, the answers OR\'d\n'
                   '        .globl  modwerk_raise_%s\nmodwerk_raise_%s:\n'
                   '        lea     -8(%%sp),%%sp\n        movem.l %%d2/%%a2,(%%sp)\n        moveq   #0,%%d2\n'
                   '        movea.l modwerk_runtime_event_row+%d,%%a2\n%s:\n        move.l  (%%a2)+,%%d0\n        beq     %s\n'
                   '        movea.l %%d0,%%a0\n        jsr     (%%a0)\n        or.l    %%d0,%%d2\n        bra     %s\n'
                   '%s:\n        move.l  %%d2,%%d0\n        movem.l (%%sp),%%d2/%%a2\n        lea     8(%%sp),%%sp\n        rts\n'
                   % (e['event'], e['prototype'], e['event'], e['event'], 4 * k, loop, end, loop, end))
    out.append('modwerk_events_code_end:\n')
    return ''.join(out)


def loader(reg):
    spans = ', '.join('{%#010xu, %du}' % (e['site'] or 0, e['length']) for e in reg['events'])  # raised: no span
    rows = ', '.join('r[%d]' % i for i in range(len(reg['events'])))
    names = ', '.join('%d %s' % (e['index'], e['event']) for e in reg['events'])
    return ('/* SPDX-License-Identifier: GPL-3.0-or-later\n'
            ' * Generated by sdk/machines/octatrack/events.py from events.json: do not edit.\n'
            ' * The Octatrack\'s events at base-owned stock sites, as hook indices after\n'
            ' * loader.h\'s RUNTIME_ENC: %s. */\n'
            '#ifndef MODWERK_RUNTIME_EVENTS_H\n#define MODWERK_RUNTIME_EVENTS_H\n'
            '#define RUNTIME_SITE_EVENTS %du\n'
            '#define RUNTIME_SITE_EVENT_SPANS { %s }\n'
            '#define RUNTIME_SITE_EVENT_ROWS(r) { %s }\n'
            '#endif\n') % (names, len(reg['events']), spans, rows)


def sdk(reg):
    out = ['/* SPDX-License-Identifier: GPL-3.0-or-later\n'
           ' * Generated by sdk/machines/octatrack/events.py from events.json: do not edit.\n'
           ' * The Octatrack\'s events at stock sites the Modwerk base owns (EVENTS.md).\n'
           ' * Subscribe with a module\'s runtime.json or build.py --subscribe EVENT:FN:ORDER;\n'
           ' * never patch these sites. Handlers use the C convention: arguments on the\n'
           ' * stack, d0-d1/a0-a1 free, everything else kept, the result in d0. */\n'
           '#ifndef MODWERK_EVENTS_H\n#define MODWERK_EVENTS_H\n#include <stdint.h>\n\n'
           '#define MODWERK_EV_PASS 0  /* the next handler, then stock */\n'
           '#define MODWERK_EV_DROP 1  /* ev_voice_bind: stock does nothing */\n'
           '#define MODWERK_EV_STOCK 2 /* ev_voice_bind: stock now, no later handler */\n']
    for e in reg['events']:
        proto = re.sub(r'^(\w+(?: \*)?)\s*f\(', r'\1 modwerk_%s(' % e['event'], e['prototype'])
        where = '%#010x' % e['site'] if e['site'] is not None else 'raised by a module'
        out.append('\n/* %s (%s): %s. %s. %s */\n#define MODWERK_%s %d\ntypedef %s;\n' % (
            e['event'], where, e['when'], e['context'][0].upper() + e['context'][1:], e['contract'],
            e['event'].upper(), e['index'], proto))
        if e['site'] is None:  # the base's entry (runtime.json "raise"): every handler's answer, OR'd
            out.append(re.sub(r'^(\w+(?: \*)?)\s*f\(', r'\1 modwerk_raise_%s(' % e['event'], e['prototype']) + ';\n')
    out.append('\n#endif\n')
    return ''.join(out)


def markdown(reg):
    out = ['# Octatrack events at base-owned stock sites\n\n'
           'Generated by `sdk/machines/octatrack/events.py` from `events.json`: edit the registry, then run\n'
           '`python3 -B sdk/machines/octatrack/events.py --write`.\n\n'
           'The Modwerk base owns these stock sites and turns them into events, as Elekloader\'s core does for\n'
           '`ev_tick` and the others (rule 4: do not patch the shared sites, subscribe). A runtime package subscribes\n'
           'with `{"event", "fn", "order"}` (a module\'s `runtime.json`, or `build.py --subscribe EVENT:FN:ORDER`);\n'
           'the loader keeps each event\'s handlers in (order, module id) order and refuses any package that\n'
           'patches one of these sites. Handlers use the C convention: arguments on the stack, d0-d1/a0-a1 free,\n'
           'everything else kept, the result in d0. C modules include `include/modwerk_events.h`.\n\n'
           '| event | site | when | C prototype | result | order | context |\n|---|---|---|---|---|---|---|\n']
    for e in reg['events']:
        where = '%#010x' % e['site'] if e['site'] is not None else 'none: a module calls `modwerk_raise_%s()`' % e['event']
        out.append('| `%s` | %s | %s | `%s` | %s | %s | %s |\n' % (
            e['event'], where, e['when'], e['prototype'], e['contract'], e['order'], e['context']))
    out.append('\n## Reviewed subscribers\n\n| event | module | handler | order | what it does | evidence |\n|---|---|---|---|---|---|\n')
    for e in reg['events']:
        for s in e['subscribers']:
            out.append('| `%s` | %s | `%s` | %d | %s | %s |\n' % (e['event'], s['module'], s['fn'], s['order'], s['does'], s['evidence']))
    raisers = [(e, r) for e in reg['events'] for r in e.get('raisers', ())]
    if raisers:
        out.append('\n## Reviewed raisers\n\nA raised event has no stock site: these modules call the base\'s entry and act on the answer.\n\n'
                   '| event | module | where | what it does with the answer | evidence |\n|---|---|---|---|---|\n')
        out += ['| `%s` | %s | `%s` | %s | %s |\n' % (e['event'], r['module'], r['fn'], r['does'], r['evidence']) for e, r in raisers]
    out.append('\n## Why this order\n\n')
    out += ['- `%s`: %s\n' % (e['event'], e['orderEvidence']) for e in reg['events']]
    out.append('\n## The sites\n\n| site | bytes | stock SHA-256 | routine |\n|---|---|---|---|\n')
    out += ['| %#010x | %d | `%s` | %s |\n' % (at, s['length'], s['guard'], s['routine']) for at, s in sorted(reg['sites'].items())]
    return ''.join(out)


def generate(reg=None):
    reg = reg or load()
    make = dict(asm=asm, loader=loader, sdk=sdk, markdown=markdown)
    return {path: make[kind](reg) for path, kind in OUTPUTS.items()}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, text in generate().items():
        target = HERE / path
        if args.write:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text)
        elif not target.is_file() or target.read_text() != text:
            stale.append(path)
    if stale:
        sys.exit('Stale generated event files (run events.py --write): ' + ', '.join(stale))


if __name__ == '__main__':
    main()
